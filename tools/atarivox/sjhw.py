#!/usr/bin/env python3
"""Run SpeakJet codes through the AtariVox engine's program in the
clock-accurate emulator (voxeng.py): the reference the FPGA must match bit
for bit, and the way to hear what the FPGA will say.

  sjhw.py out.wav CODES...          codes as numbers
  sjhw.py out.wav --log tb.log      tb_load +voxlog / stella_voxlog.py output
  sjhw.py --build DIR               write the engine's ROM images for the RTL
                                    (vox_irom.hex/.mif, vox_drom.hex/.mif)

Bytes go into the 64-byte FIFO as a game sends them: one whenever the FIFO
is under half full (the DOWN pin high). The WAV is the engine's output at
16,384 Hz.

MIT licence, as the rest of the Pocket port's own code.
"""
import os
import re
import struct
import sys
import wave

import vox_rom
import voxeng
import voxprog

CLK = 14318182          # clk_sys, NTSC
TICK_DIV = 874          # 16,384 Hz from clk_sys
BYTE_CLKS = 7440        # a byte on the wire: 10 bits of 744 clk_sys


def build():
    rom, info = vox_rom.build()
    words, labels, regs, prog = voxeng.assemble(voxprog.source(), {**vox_rom.CONSTS})
    return words, rom, labels, info


def run(codes, tail_ms=300, words=None, rom=None, schedule=None):
    """Feed codes (flow-controlled, or at the clocks in schedule) and run
    until they are spoken plus tail_ms. Returns the engine."""
    if words is None:
        words, rom, _, _ = build()
    e = voxeng.Engine(words, rom, TICK_DIV)
    if schedule is not None:
        for clk, kind, v in schedule:
            e.schedule(clk, kind, v)
        end = max([c for c, _, _ in schedule] + [0])
        e.run_until(end + int(tail_ms * CLK / 1000))
        return e
    pending = list(codes)
    next_free = 0
    quiet = 0
    while True:
        e.run_until(e.clk + 2 * TICK_DIV)
        if pending and len(e.fifo) < 32 and e.clk >= next_free:
            e.push_now(pending.pop(0))
            next_free = e.clk + BYTE_CLKS
        if not pending and not e.fifo:
            quiet += 1
            if quiet * 2 * TICK_DIV > tail_ms * CLK / 1000 and _idle(e):
                break
        if e.clk > CLK * 120:
            break
    return e


def _idle(e):
    return e.mem[31] == 0 and e.mem[voxprog.MEM["P_VALID"]] == 0


def write_wav(path, samples, rate=16384, gain=8):
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(struct.pack(f"<{len(samples)}h",
                                  *(max(-32768, min(32767, s * gain)) for s in samples)))


def hexfile(path, values, width):
    digits = (width + 3) // 4
    with open(path, "w") as f:
        for v in values:
            f.write(f"{v & ((1 << width) - 1):0{digits}x}\n")


def miffile(path, values, width, depth):
    with open(path, "w") as f:
        f.write(f"-- generated by tools/atarivox/sjhw.py --build\nWIDTH={width};\nDEPTH={depth};\n"
                "ADDRESS_RADIX=HEX;\nDATA_RADIX=HEX;\nCONTENT BEGIN\n")
        for i in range(depth):
            v = values[i] if i < len(values) else 0
            f.write(f"  {i:x} : {v & ((1 << width) - 1):x};\n")
        f.write("END;\n")


def main():
    if sys.argv[1] == "--build":
        out = sys.argv[2]
        words, rom, labels, info = build()
        hexfile(os.path.join(out, "vox_irom.hex"), words + [0] * (voxeng.IROM_WORDS - len(words)), 40)
        miffile(os.path.join(out, "vox_irom.mif"), words, 40, voxeng.IROM_WORDS)
        hexfile(os.path.join(out, "vox_drom.hex"), rom, 20)
        miffile(os.path.join(out, "vox_drom.mif"), rom, 20, voxeng.ROM_WORDS)
        print(f"program {len(words)} of {voxeng.IROM_WORDS} words; data ROM: {info}")
        return
    out = sys.argv[1]
    if len(sys.argv) > 3 and sys.argv[2] == "--log":
        codes = [int(m.group(1)) for m in re.finditer(r"VOX [\d.]+ ms:\s+(\d+)",
                                                      open(sys.argv[3], errors="replace").read())]
    else:
        codes = [int(x, 0) for x in sys.argv[2:]]
    e = run(codes)
    samples = [s for _, s in e.out]
    write_wav(out, samples)
    print(f"{out}: {len(codes)} codes, {len(samples) / 16384:.2f} s, "
          f"{e.icount} instructions, ticks missed {e.missed}")


if __name__ == "__main__":
    main()
