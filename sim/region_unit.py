#!/usr/bin/env python3
"""tb_region's unit under test: the region logic of atari7800_pocket.sv, cut
out of the wrapper as the tree has it, into a module of its own.

  region_unit.py WRAPPER OUT [VARIANT]

WRAPPER is src/fpga/core/atari7800_pocket.sv. OUT gets module region_unit:
the DARIA retune counter (daria_rt_cnt, the block after "wire daria_hold,
daria_arm, daria_rt_pend;") and the whole region_pll block, from "reg
region_pll" to the `endif after its plain-build branch, both copied as they
are, with old_cart_download and pll_busy_s as the wrapper registers them.
Compiled with POCKET_DARIA it is the DARIA build's logic, without it the
plain build's. The inputs the wrapper computes elsewhere (region_select,
cart_is_7800, tia_mode, tia_en, daria_reset, daria_arm) are ports, which
tb_region.sv models.

VARIANT plants one change (each replacement must match exactly once):
  rtl2    RTL-2 undone: the withdrawal takes daria_rgn's old value
  rtl1    RTL-1 undone: region_pll frozen in an A78's header too
  old     both undone: 2.2.1's region logic
  sketch  RTL-1 as first sketched: region_pll follows region_select with a
          retune pending through the whole A78 download and the clock after
          it, not only in its header
SPDX-License-Identifier: MIT
"""
import re, sys

VARIANTS = {
    "rtl2": [("region_pll <= daria_rgn_nx;", "region_pll <= daria_rgn;")],
    "rtl1": [("(!daria_rt_pend || daria_a78_hdr)", "!daria_rt_pend")],
    "sketch": [("wire daria_a78_hdr = cart_download & cart_is_7800 & (ioctl_addr < 25'd128);",
                "wire daria_a78_hdr = (cart_download | old_cart_download) & cart_is_7800;")],
}
VARIANTS["old"] = VARIANTS["rtl2"] + VARIANTS["rtl1"]

HEAD = """// Generated by sim/region_unit.py from %s%s: not a source file.
`default_nettype none
module region_unit (
	input  wire        clk_sys,
	input  wire        pll_busy,
	input  wire        cart_download,
	input  wire        cart_is_7800,
	input  wire [24:0] ioctl_addr,
	input  wire        region_select,
	input  wire        tia_mode,
	input  wire        tia_en,
	input  wire        daria_reset,
	input  wire        daria_arm,
	output wire        is_pal_o,
	output wire        rgn_o,
	output wire  [3:0] rt_cnt_o
);
reg old_cart_download = 1'b0;
reg [1:0] pll_busy_s = 2'b00;
always @(posedge clk_sys) begin
	old_cart_download <= cart_download;
	pll_busy_s <= {pll_busy_s[0], pll_busy};
end
`ifdef POCKET_DARIA
wire daria_rt_pend;
"""

TAIL = """
assign is_pal_o = region_pll;
`ifdef POCKET_DARIA
assign rgn_o = daria_rgn;
assign rt_cnt_o = daria_rt_cnt;
`else
assign rgn_o = region_pll;
assign rt_cnt_o = 4'd0;
`endif
endmodule
"""


def cut(t, start, end, what):
    i = t.find(start)
    if i < 0 or t.find(start, i + 1) >= 0:
        sys.exit("region_unit.py: %s: the start %r is not in the wrapper once" % (what, start))
    j = t.find(end, i)
    if j < 0:
        sys.exit("region_unit.py: %s: no end %r after its start" % (what, end))
    return t[i:j + len(end)]


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    var = sys.argv[3] if len(sys.argv) == 4 else ""
    t = open(src).read()
    # the counter, without its declaration line (daria_hold and daria_arm are no part of it)
    cnt = cut(t, "wire       daria_hold, daria_arm, daria_rt_pend;\n", "`endif\n", "the retune counter")
    cnt = cnt.split("\n", 1)[1][:-len("`endif\n")]
    # the region block: its power-up pragma line, then through the `endif after the plain build's branch
    rb = cut(t, "/* verilator lint_off PROCASSINIT */\nreg region_pll = 1'b0;\n", "\n`endif\n", "the region block")
    if "daria_rt_mask" not in rb or "`else" not in rb:
        sys.exit("region_unit.py: the region block cut does not end after daria_rt_mask's `else branch")
    body = cnt + "`endif\n" + rb
    if var:
        if var not in VARIANTS:
            sys.exit("region_unit.py: unknown variant %s (%s)" % (var, " ".join(sorted(VARIANTS))))
        for a, b in VARIANTS[var]:
            if body.count(a) != 1:
                sys.exit("region_unit.py: variant %s: %r occurs %d times, not once" % (var, a, body.count(a)))
            body = body.replace(a, b)
    open(out, "w").write(HEAD % (re.sub(r".*/src/", "src/", src), ", variant " + var if var else "") + body + TAIL)


if __name__ == "__main__":
    main()
