def v_deps(k, producers, bl=False):
    t = T("v_deps%d" % k, "Register dependences: each producer of r3, then each consumer position,\n"
          "straight after and with one instruction between.")
    for pname, setup, prod, gives_v in producers:
        for cname, cons, needs_v in CONSUMERS:
            if needs_v and not gives_v:
                continue
            for gap in (False, True):
                t.e("ldr\tr7, =0x00000013", "mov\tr8, #3", "mov\tr2, #0x55", "mov\tr0, #0", "mov\tr1, #0")
                t.e(*setup)
                t.e(*prod)
                if gap:
                    t.e("mov\tr9, #0")
                t.e(*cons)
                t.e("MIX\tr0", "MIX\tr1", "MIX\tr3", "MIXF", "msr\tcpsr_f, #0")
            t.sig()
    if bl:      # the link register, used at once
        for use in ("add\tr0, lr, #4", "str\tlr, [r12, #0xd0]", "mov\tr0, lr, lsl r8",
                    "mul\tr0, lr, r7", "cmp\tlr, r7", "ldr\tr0, [lr]"):
            lab = t.label()
            t.e("mov\tr0, #0", "bl\t" + lab, lab + ":", use, "MIX\tr0", "MIX\tlr", "MIXF")
        t.sig()
    blk_hash(t, 0xc0, 0x100)
    t.tail += ["vword:\t.word\t0x%x" % V]
    return t, False


def v_wb():
    t = T("v_wb", "Rd == Rn with write-back (a load keeps the loaded value, a store the\n"
          "old base, as on the ARM7TDMI); Rm == Rn and Rd == Rm; the T forms.")
    for op, sz in (("ldr", 4), ("str", 4), ("ldrb", 1), ("strb", 1), ("ldrh", 2), ("strh", 2),
                   ("ldrsb", 1), ("ldrsh", 2)):
        for mode in ("[r3, #%d]!", "[r3], #%d", "[r3, #-%d]!", "[r3], #-%d",
                     "[r3, r2]!", "[r3], r2", "[r3, -r2]!", "[r3], -r2"):
            am = mode % (4 * sz) if "%" in mode else mode
            t.e("add\tr3, r12, #0x80", "mov\tr2, #%d" % (2 * sz), op + "\tr3, " + am, "MIX\tr3")
            blk_hash(t, 0x70, 0x90)
        t.sig()
    for ins in ("ldr\tr3, [r3, -r3]!", "ldrb\tr3, [r3, -r3]", "ldrh\tr4, [r3, -r3]!",
                "ldr\tr4, [r3, r4]!", "ldr\tr4, [r3], r4", "ldrsh\tr4, [r3, r4]!",
                "ldrt\tr3, [r3], #4", "ldrbt\tr3, [r3], #-1", "strt\tr3, [r3], #4",
                "strbt\tr3, [r3], #1", "ldrt\tr0, [r3], r4", "strbt\tr0, [r3], -r4, lsl #1"):
        t.e("add\tr3, r12, #0x80", "mov\tr4, #8", "mov\tr0, #0x77", ins, "MIX\tr3", "MIX\tr4", "MIX\tr0")
        blk_hash(t, 0x70, 0x90)
        t.sig()
    return t, False


def v_align():
    t = T("v_align", "Loads at every byte offset from RAM, ROM, the asset window and the\n"
          "peripheral; unaligned STR and STRH, read back.")
    t.e("ldr\tr4, =ASSET", "ldr\tr5, =rodata", "ldr\tr6, =MMIO", "add\tr7, r12, #0x20")
    for base in ("r7", "r5", "r4", "r6"):
        for off in range(8):
            for op in ("ldr", "ldrh", "ldrsh", "ldrb", "ldrsb"):
                t.e("%s\tr0, [%s, #%d]" % (op, base, off), "MIX\tr0")
            neg = "-" if base in ("r7", "r5") else ""
            t.e("mov\tr1, #%d" % off, "ldrh\tr0, [%s, r1]" % base, "MIX\tr0",
                "ldrsh\tr0, [%s, %sr1]" % (base, neg), "MIX\tr0", "ldr\tr0, [%s, %sr1]" % (base, neg), "MIX\tr0")
        t.sig()
    t.e("ldr\tr4, =ASSET + 0x3f8")      # the last bytes of the 1 KiB asset image
    for off in range(8):
        for op in ("ldrb", "ldrsb", "ldrh", "ldrsh", "ldr"):
            t.e("%s\tr0, [r4, #%d]" % (op, off), "MIX\tr0")
    t.sig()
    for off in range(4):
        t.e("ldr\tr1, =0xa1b2c3d4", "add\tr2, r12, #0x60", "str\tr1, [r2, #%d]" % off,
            "strh\tr1, [r2, #%d]" % (off + 4), "mov\tr3, #%d" % (off + 8), "str\tr1, [r2, r3]",
            "add\tr3, r3, #4", "strh\tr1, [r2, r3]")
        blk_hash(t, 0x5c, 0x78)
        t.sig()
    t.e("add\tr3, r12, #0x41", "ldr\tr0, [r3], #4", "MIX\tr0", "MIX\tr3",
        "ldrh\tr0, [r3, #2]!", "MIX\tr0", "MIX\tr3", "ldrsh\tr0, [r3, #-2]!", "MIX\tr0", "MIX\tr3")
    t.tail += ["rodata:\t.word\t0x80ff7f01, 0xfe0280c3, 0x11223344, 0x8899aabb"]
    return t, False


def v_blkx():
    t = T("v_blkx", "LDM/STM with the base in the list: lowest, middle, highest and alone,\n"
          "all four modes, with and without write-back (ARM7TDMI results).")
    for base, l in (("r0", "{r0, r2, r5}"), ("r2", "{r0, r2, r5}"), ("r5", "{r0, r2, r5}"),
                    ("r4", "{r4}"), ("r14", "{r0-r8, r14}"), ("r1", "{r0-r8, r14}")):
        for mode in ("ia", "ib", "da", "db"):
            for w in ("", "!"):
                for ld in ("stm", "ldm"):
                    load_regs(t)
                    t.e("add\t%s, r12, #0x80" % base, "%s%s\t%s%s, %s" % (ld, mode, base, w, l))
                    for r in ("r0", "r1", "r2", "r4", "r5", "r8", "r14"):
                        t.e("MIX\t" + r)
                    blk_hash(t)
                    t.sig()
    t.tail += [RINIT]
    return t, False


def v_mmio():
    t = T("v_mmio", "Peripheral accesses under every NZCV and condition: failed reads must\n"
          "not pop and failed writes must not push; offsets, write-back, sizes.")
    t.e("ldr\tr5, =MMIO", "mov\tr6, #0", "outer:")
    for c in CONDS[:-1]:
        t.e("mov\tr0, #0x33", "msr\tcpsr_f, r6", "ldr%s\tr0, [r5, #4]" % c, "MIX\tr0",
            "msr\tcpsr_f, r6", "str%s\tr6, [r5, #0x10]" % c,
            "mov\tr1, #0x14", "msr\tcpsr_f, r6", "ldr%s\tr0, [r5, r1]" % c, "MIX\tr0")
    t.sig()
    t.e("add\tr6, r6, #0x10000000", "cmp\tr6, #0", "bne\touter")
    t.pool()
    t.e("ldr\tr7, =0x12345678", "ldr\tr0, [r5, #0x14]", "MIX\tr0", "mov\tr1, #0x10", "str\tr7, [r5, r1]",
        "ldr\tr0, [r5, #0x14]", "MIX\tr0", "strb\tr7, [r5, #0x10]", "strh\tr7, [r5, #0x10]",
        "ldr\tr0, [r5, #0x14]", "MIX\tr0", "add\tr4, r5, #0x10", "str\tr7, [r4], #4", "MIX\tr4",
        "ldr\tr0, [r4, #-4]!", "MIX\tr0", "MIX\tr4", "mov\tr4, r5", "ldr\tr4, [r4]", "MIX\tr4",
        "ldrb\tr0, [r5, #3]", "MIX\tr0", "ldrh\tr0, [r5, #2]", "MIX\tr0", "ldrsh\tr0, [r5]", "MIX\tr0",
        "ldrsb\tr0, [r5, #1]", "MIX\tr0", "ldr\tr0, [r5, #0xfc]", "MIX\tr0", "str\tr0, [r5, #0xfc]",
        "mov\tr1, #0x14", "ldr\tr0, [r5, r1]!", "MIX\tr0", "MIX\tr5")
    t.sig()
    return t, False


def v_nv():
    t = T("v_nv", "The NV condition: never executed on ARMv4, whatever the encoding\n"
          "(ARMv5 gives some of these meanings of their own).")
    t.e("ldr\tr1, =0x10000000", "mov\tr0, #0x11", "mov\tr2, #0x22")
    for w in (0xF0810002, 0xF3A00001, 0xF1B00001, 0xF5910000, 0xF58C0000, 0xF1DC00B0,
              0xF0000291, 0xF0800291, 0xF89C0003, 0xF88C0003, 0xFA000010, 0xFB000010,
              0xF12FFF11, 0xF10F0000, 0xF128F001, 0xF321F010, 0xFF000000, 0xFE000000,
              0xF1A0F00E, 0xF1000090, 0xF6000010, 0xF8BD8000, 0xF4910000, 0xF7D2F003):
        t.e(".word\t0x%08x" % w, "MIX\tr0", "MIX\tr2", "MIXF")
    t.sig()
    return t, False


def v_unpred():
    t = T("v_unpred", "Register overlaps ARMv4 leaves UNPREDICTABLE that the core runs as\n"
          "the ARM7TDMI does: MUL/MLA Rd == Rm, UMULL RdLo/RdHi == Rm.")
    for a, b in ((3, 5), (0xffffffff, 0x80000001), (0x12345678, 0x9abcdef0)):
        t.e("ldr\tr1, =0x%x" % a, "ldr\tr2, =0x%x" % b,
            "mov\tr3, r1", ".word\t0xe0030293", "MIX\tr3",          # mul r3, r3, r2
            "mov\tr3, r1", ".word\t0xe0231293", "MIX\tr3",          # mla r3, r3, r2, r1
            "mov\tr3, r1", ".word\t0xe0843293", "MIX\tr3", "MIX\tr4",   # umull r3, r4, r3, r2
            "mov\tr4, r1", ".word\t0xe0843294", "MIX\tr3", "MIX\tr4",   # umull r3, r4, r4, r2
            "mov\tr4, r2", "umull\tr3, r4, r1, r4", "MIX\tr3", "MIX\tr4")
        t.sig()
    return t, False


