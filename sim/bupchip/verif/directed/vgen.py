def v_shift():
    t = T("v_shift", "Barrel shifter: types x amounts x S x carry in, through logical and\n"
          "arithmetic operations; scaled register offsets with the amount-0 encodings.")
    vals = [0, 1, 0x80000000, 0x80000001, 0x7ffffffe, 0xffffffff, 0xaaaaaaaa, 0x55555555,
            0x12345678, 0x0000ffff]
    t.e("ldr\tr5, =0x7fffffff", "ldr\tr6, =0xf0f0f0f0")

    def body(sh):
        lab = t.label()
        t.e("ldr\tr8, =vals", "mov\tr7, #%d" % len(vals), lab + ":", "ldr\tr4, [r8], #4")
        for f in (0x5, 0xA):            # Z and V set, C clear / N and C set
            for op in ("movs\tr0, r4, %s", "mov\tr0, r4, %s", "adcs\tr0, r5, r4, %s",
                       "rscs\tr0, r5, r4, %s", "bics\tr0, r6, r4, %s", "teq\tr6, r4, %s",
                       "cmn\tr5, r4, %s"):
                setf(t, f)
                t.e(op % sh)
                if not op.startswith(("teq", "cmn")):
                    t.e("MIX\tr0")
                t.e("MIXF")
        t.sig()
        t.e("subs\tr7, r7, #1", "bne\t" + lab)

    for sh in ("lsl #1", "lsl #31", "lsl #0", "lsr #1", "lsr #31", "lsr #32", "asr #1",
               "asr #31", "asr #32", "ror #1", "ror #31", "rrx"):
        body(sh)
        t.pool()
    for ty in ("lsl", "lsr", "asr", "ror"):
        lab = t.label()
        t.e("ldr\tr3, =amts", lab + "a:", "ldr\tr2, [r3], #4", "cmp\tr2, #0x5a", "beq\t%sz" % lab)
        body(ty + " r2")
        t.e("b\t%sa" % lab, lab + "z:")
        t.pool()
    # scaled register offsets (bytes, or aligned words)
    t.e("add\tr1, r12, #0x80")
    for rm, flags, ins in ((0x40, 0, "ldrb\tr0, [r1, r2, lsr #32]"),
                           (0x40, 2, "ldrb\tr0, [r1, r2, asr #32]"),
                           (-0x40, 0, "ldrb\tr0, [r1, r2, asr #32]"),
                           (-0x40, 0, "ldrb\tr0, [r1, -r2, asr #32]"),
                           (0x40, 0, "ldrb\tr0, [r1, r2, rrx]"),
                           (0x41, 0, "ldrb\tr0, [r1, -r2, rrx]"),
                           (0x40, 0, "ldr\tr0, [r1, r2, lsl #0]"),
                           (0x20, 0, "ldr\tr0, [r1, -r2, ror #31]"),
                           (0x40, 2, "ldr\tr0, [r1, r2, lsr #32]"),
                           (0x41, 0, "strb\tr6, [r1, r2, rrx]"),
                           (0x40, 0, "str\tr6, [r1, -r2, lsr #3]!")):
        t.e("ldr\tr2, =0x%x" % (rm & 0xffffffff))
        setf(t, flags)
        t.e(ins, "MIX\tr0", "MIX\tr1", "MIXF")
        t.sig()
    blk_hash(t, 0x60, 0x100)
    t.tail += ["vals:\t.word\t" + ", ".join("0x%08x" % v for v in vals),
               "amts:\t.word\t0, 1, 31, 32, 33, 64, 224, 255, 256, 0x1f1, 0xffffff20, 0x80000021, 0x5a"]
    return t, True


def v_imm():
    t = T("v_imm", "Rotated immediates: the carry is bit 31 of the value when the rotation\n"
          "is not 0, and unchanged when it is; every data-processing opcode.")
    # (imm8, rot): (4, 0) and (1, 15) are both 4, (0x80, 0) and (0x08, 14) both
    # 0x80, (0, 0) and (0, 5) both 0
    encs = [(4, 0), (1, 15), (0xff, 0), (0xff, 4), (0x02, 1), (0x80, 0), (0x08, 14), (0xc0, 1),
            (0x01, 1), (0x3f, 3), (0, 0), (0, 5)]
    t.e("ldr\tr4, =0x80000001", "ldr\tr5, =0x7fffffff")
    for op in range(16):
        rn = 0 if op in (0xd, 0xf) else (4 if op % 2 == 0 else 5)
        for imm8, rot in encs:
            for f in (0x5, 0xA):
                setf(t, f)
                t.e(".word\t0x%08x" % (0xE2100000 | op << 21 | rn << 16 | rot << 8 | imm8))
                t.e("MIX\tr0", "MIXF")
        t.sig()
    for op in (0, 2, 4, 5, 0xd, 0xf):       # without S: the flags stay
        rn = 0 if op in (0xd, 0xf) else 4
        setf(t, 0xA)
        t.e(".word\t0x%08x" % (0xE2000000 | op << 21 | rn << 16 | 1 << 8 | 2), "MIX\tr0", "MIXF")
    t.sig()
    return t, True


def v_cond():
    t = T("v_cond", "Each NZCV value against the 15 conditions other than NV, for each\n"
          "instruction class; a failed condition must leave no trace.")
    t.e("mov\tr6, #0", "outer:", "SIG\tr6", "ldr\tr1, =0x7fffffff", "mov\tr2, #1")

    def each(setup, op, record):
        for c in CONDS:
            t.e(*[s.replace("CC", c) for s in setup])
            t.e("msr\tcpsr_f, r6")
            t.e(*[o.replace("CC", c) for o in op])
            t.e(*[r.replace("CC", c) for r in record])
        t.sig()

    restore = []
    for off in (0x78, 0x7c, 0x80, 0x84):
        restore += ["ldr\tr4, =0x%08x" % pattern(off), "str\tr4, [r12, #0x%x]" % off]
    each([], ["addsCC\tr0, r1, r2"], ["MIX\tr0", "MIXF"])
    each(["mov\tr0, #0"], ["bCC\t1f", "orr\tr0, r0, #1", "1:"], ["MIX\tr0"])
    each(["mov\tr0, #0", "mov\tlr, #0"], ["blCC\tvsub"], ["MIX\tr0", "MIX\tlr"])
    each(["mov\tr0, #0", "adr\tr7, 1f"], ["bxCC\tr7", "orr\tr0, r0, #1", "1:"], ["MIX\tr0"])
    each(["mov\tr0, #0"], ["ldrCC\tr0, [r12, #4]"], ["MIX\tr0"])
    each(["mov\tr0, #0", "str\tr0, [r12, #0x40]", "ldr\tr3, =0x11223344"],
         ["strCC\tr3, [r12, #0x40]"], ["ldr\tr0, [r12, #0x40]", "MIX\tr0"])
    each(["mov\tr0, #0", "mov\tr3, #0", "mov\tr4, #0x99", "str\tr0, [r12, #0x44]"],
         ["ldrhCC\tr0, [r12, #6]", "msr\tcpsr_f, r6", "ldrsbCC\tr3, [r12, #7]", "msr\tcpsr_f, r6",
          "strbCC\tr4, [r12, #0x45]"],
         ["MIX\tr0", "MIX\tr3", "ldr\tr0, [r12, #0x44]", "MIX\tr0"])
    each(["mov\tr0, #5", "mov\tr3, #7"], ["mulCC\tr0, r1, r1", "msr\tcpsr_f, r6", "mlaCC\tr3, r1, r1, r2"],
         ["MIX\tr0", "MIX\tr3", "MIXF"])
    each(["mov\tr0, #5", "mov\tr3, #7"], ["umullCC\tr0, r3, r1, r1"], ["MIX\tr0", "MIX\tr3", "MIXF"])
    each(["mov\tr0, #5", "mov\tr3, #7", "add\tr9, r12, #0x80", "ldr\tr4, =0xabcdef01",
          "ldr\tr5, =0x10fedcba"],
         ["ldmiaCC\tr9!, {r0, r3}", "msr\tcpsr_f, r6", "stmdbCC\tr9!, {r4, r5}"],
         ["MIX\tr0", "MIX\tr3", "MIX\tr9", "ldr\tr0, [r12, #0x78]", "MIX\tr0", "ldr\tr0, [r12, #0x7c]",
          "MIX\tr0", "ldr\tr0, [r12, #0x80]", "MIX\tr0", "ldr\tr0, [r12, #0x84]", "MIX\tr0"] + restore)
    each(["mov\tr0, #5", "mov\tr3, #3"], ["movsCC\tr0, r1, lsl r3"], ["MIX\tr0", "MIXF"])
    each([], ["msrCC\tcpsr_f, #0x60000000"], ["MIXF"])
    each(["mov\tr0, #5"], ["mrsCC\tr0, cpsr"], ["MIX\tr0"])
    each(["mov\tr0, #0", "adr\tr7, 1f", "str\tr7, [r12, #0x48]", "add\tr7, r12, #0x48"],
         ["ldrCC\tpc, [r7]", "orr\tr0, r0, #1", "1:"], ["MIX\tr0"])
    t.e("add\tr6, r6, #0x10000000", "cmp\tr6, #0", "bne\touter")
    t.tail += ["vsub:\tadd\tr0, r0, #1", "\tbx\tlr"]
    return t, True


def v_mul():
    t = T("v_mul", "MUL, MLA and UMULL on corner values; the overlapping register forms\n"
          "ARMv4 defines; flags kept.")
    vals = [0, 1, 2, 0xffffffff, 0x80000000, 0x7fffffff, 0x0000ffff, 0x00010000, 0x12345678,
            0xfffffffe, 0x80000001, 0xdeadbeef]
    t.e("mov\tr7, #0", "1:", "ldr\tr8, =vals", "ldr\tr1, [r8, r7, lsl #2]", "mov\tr6, #0",
        "2:", "ldr\tr2, [r8, r6, lsl #2]", "eor\tr3, r1, r2, ror #5")
    setf(t, 0xA)
    t.e("mul\tr0, r1, r2", "MIX\tr0",
        "mla\tr0, r1, r2, r3", "MIX\tr0",
        "umull\tr4, r5, r1, r2", "MIX\tr4", "MIX\tr5",
        "mul\tr0, r2, r2", "MIX\tr0",
        "mov\tr0, r2", "mul\tr0, r1, r0", "MIX\tr0",
        "mov\tr4, r3", "mla\tr4, r1, r2, r4", "MIX\tr4",
        "mov\tr5, r2", "umull\tr4, r5, r1, r5", "MIX\tr4", "MIX\tr5",
        "mov\tr4, r2", "umull\tr4, r5, r1, r4", "MIX\tr4", "MIX\tr5",
        "MIXF", "SIG\tr10",
        "add\tr6, r6, #1", "cmp\tr6, #%d" % len(vals), "bne\t2b",
        "add\tr7, r7, #1", "cmp\tr7, #%d" % len(vals), "bne\t1b")
    t.tail += ["vals:\t.word\t" + ", ".join("0x%08x" % v for v in vals)]
    return t, True


def v_blk():
    t = T("v_blk", "LDM/STM: the four modes, with and without write-back, several lists\n"
          "(the base never in the list); push/pop; stmib sp.")
    for l in ("{r0}", "{r1, r3}", "{r0-r8}", "{r0-r8, r14}", "{r2, r7, r14}"):
        for mode in ("ia", "ib", "da", "db"):
            for w in ("", "!"):
                for ld in ("stm", "ldm"):
                    load_regs(t)
                    t.e("add\tr9, r12, #0x80", "%s%s\tr9%s, %s" % (ld, mode, w, l), "MIX\tr9")
                    for r in ("r0", "r1", "r2", "r3", "r7", "r8", "r14"):
                        t.e("MIX\t" + r)
                    if ld == "stm":
                        blk_hash(t)
                    t.sig()
    load_regs(t)
    t.e("push\t{r0-r8, r14}", "MIX\tsp", "pop\t{r4-r8, r14}", "pop\t{r0-r3}",
        "MIX\tsp", "MIX\tr0", "MIX\tr4", "MIX\tr14", "sub\tsp, sp, #16", "stmib\tsp, {r0, r1}",
        "ldmia\tsp, {r2-r5}", "add\tsp, sp, #16", "MIX\tr3", "MIX\tr4", "MIX\tr5", "MIX\tsp")
    t.sig()
    t.tail += [RINIT]
    return t, True


