#!/usr/bin/env python3
"""Generate the verifier's directed tests for the BupChip CPU, as .S files.

  vgen.py OUTDIR            writes OUTDIR/v_*.S and OUTDIR/iss.txt

Written independently of ../../s1/directed/ and the other tests here, from
the lists in docs/BUPCHIP_CORE.md ("Verification plan" and "ARMv4
behaviours that must be exact"). Each test uses the shared frame
../../s1/directed/common.inc (included by absolute path, so that
../isa/run_isa.sh can build the files where they are written) and folds its
results into r10 with MIX/MIXF, storing r10 to the signature after each
group, so that a test stays inside the 8 KiB signature. iss.txt lists the
tests that stay inside the subset ARMv4 and ARMv5 agree on: run_vfy.sh also
checks those against Unicorn. Every test runs in lockstep with the reference.

  v_shift   each shift type by register amounts 0, 1, 31, 32, 33, 64, 224,
            255, 256, 0x1f1, 0xffffff20 and 0x80000021, and by immediate 1
            and 31, LSL #0, LSR #32, ASR #32 and RRX, through MOV, MOVS,
            ADCS, RSCS, BICS, TEQ and CMN, with C (and the other flags) 0
            and 1, on ten values; scaled register offsets with LSR #32, ASR
            #32, RRX and ROR
  v_imm     rotated immediates through all 16 opcodes with S: rotation 0
            (C unchanged) against a non-zero rotation of the same value (C
            = bit 31), including 0 rotated; the same without S
  v_cond    each of the 16 NZCV values against the 15 conditions other than
            NV, for 14 classes: ALU with S, B, BL, BX, LDR, STR,
            LDRH/LDRSB/STRB, MUL/MLA, UMULL, LDM/STM with write-back, shift
            by register, MSR, MRS, LDR pc
  v_mul     MUL, MLA and UMULL on 12 x 12 corner values; the overlaps ARMv4
            defines (MUL Rd == Rs, Rm == Rs; MLA Rd == Rn; UMULL RdLo or
            RdHi == Rs); flags kept
  v_blk     LDM/STM in the four modes, with and without write-back, lists of
            1, 2, 3, 9 and 10 registers (base not in the list); push/pop;
            stmib sp without write-back
  v_deps1-5 each producer of a register (loads from RAM, ROM, the asset
            window and the peripheral, post-indexed too; ALU, MOVS with a
            register shift, MUL, MLA, UMULL low and high, LDM first and
            last, base write-back of LDR, LDRH and LDM; MRS) followed at
            once, and after one other instruction, by each consumer
            position (Rn, Rm, Rm shifted, Rs, Rm and Rn of a register
            shift, MUL Rm/Rs, MLA Rn, UMULL Rm, store data of one- and
            two-clock stores, STRH and STM data, CMP, MSR, the base of a
            load, a load with write-back, a store and an LDM, a register
            offset); BL's link used at once
  v_wb      Rd == Rn with write-back for every transfer size, pre and post
            index, immediate and register offset, up and down; Rm == Rn and
            Rd == Rm for loads; LDRT/STRT/LDRBT/STRBT
  v_align   LDR, LDRH, LDRSH, LDRB and LDRSB at byte offsets 0-7 from RAM,
            ROM, the asset window (and its last eight bytes) and the
            peripheral; STR and STRH at every offset, read back; an
            unaligned base with write-back
  v_blkx    LDM/STM with the base in the list: lowest, middle, highest and
            alone, all four modes, with and without write-back
  v_mmio    peripheral reads and writes under every NZCV and condition (a
            failed read of 0x04 must not pop, a failed write of 0x10 not
            push); register offsets, write-back of the base, byte and
            halfword stores, sub-word reads, a load into its own base, the
            last word of the window
  v_nv      the NV condition (never, on ARMv4) on every class, including
            encodings the core halts on when they execute
  v_unpred  MUL and MLA Rd == Rm, UMULL RdLo or RdHi == Rm: the ARM7TDMI's
            results (or a halt, which run.sh reports)
SPDX-License-Identifier: MIT
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
COMMON = os.path.normpath(os.path.join(HERE, "..", "..", "s1", "directed", "common.inc"))
CONDS = ["eq", "ne", "cs", "cc", "mi", "pl", "vs", "vc", "hi", "ls", "ge", "lt", "gt", "le", "al"]
RINIT = ("rinit:\t.word\t0x01010101, 0x02020202, 0x03030303, 0x04040404, 0x05050505, "
         "0x06060606, 0x07070707, 0x08080808, 0x09090909, 0x0e0e0e0e")


def pattern(off):
    """common.inc's data-area word at byte offset off."""
    return (0x83828180 + 0x04040404 * (off // 4)) & 0xffffffff


class T:
    """One test file: instructions, with a literal pool every so often."""

    def __init__(self, name, desc):
        self.name, self.n, self.lab = name, 0, 0
        self.lines = ["@ " + l for l in desc.strip().split("\n")]
        self.lines += ["@ Generated by vgen.py. SPDX-License-Identifier: MIT",
                       '#include "%s"' % COMMON, "\tSTART",
                       "\t.macro MIX reg", "\tadd\tr10, \\reg, r10, ror #27", "\t.endm",
                       "\t.macro MIXF", "\tmrs\tr9, cpsr", "\tadd\tr10, r9, r10, ror #27", "\t.endm",
                       "\tmov\tr10, #0"]
        self.tail = []

    def label(self):
        self.lab += 1
        return "L%d" % self.lab

    def e(self, *ins):
        for i in ins:
            if i.endswith(":"):
                self.lines.append(i)
            else:
                self.lines.append("\t" + i)
                self.n += 1
        if self.n > 200:
            self.pool()

    def pool(self):
        self.lines.append("\tPOOL")
        self.n = 0

    def sig(self):
        self.e("SIG\tr10")

    def text(self):
        return "\n".join(self.lines + ["\tSIG\tr10", "\tb\tvend", "\t.align\t2"] + self.tail +
                         ["vend:", "\tEND", ""])


def setf(t, nzcv):
    t.e("msr\tcpsr_f, #0x%x" % (nzcv << 28))


def blk_hash(t, lo=0x40, hi=0xc0):
    """Fold the data-area words [lo, hi) into r10 (uses r0, r7, r8)."""
    lab = t.label()
    t.e("add\tr8, r12, #0x%x" % lo, "mov\tr7, #%d" % ((hi - lo) // 4), lab + ":",
        "ldr\tr0, [r8], #4", "MIX\tr0", "subs\tr7, r7, #1", "bne\t" + lab)


def load_regs(t):
    t.e("ldr\tr0, =rinit", "ldmia\tr0, {r0-r8, r14}")


